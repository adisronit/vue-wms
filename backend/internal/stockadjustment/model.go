// Package stockadjustment implements controlled inventory correction:
// Stock Adjustment -> Approve -> Inventory AddStock/RemoveStock ->
// Inventory Ledger. It calls Phase 5's internal/inventory (AddStockTx
// on INCREASE, RemoveStockTx on DECREASE) for the one and only stock
// mutation this workflow performs — at Approve time, never at Create —
// so a DRAFT or PENDING adjustment has zero effect on inventory until a
// separate approver acts on it.
//
// Matches StockAdjustmentView.vue — a single list+drawer screen (the
// same shape Picking/Shipping already established). See
// PROJECT_STATUS.md for the reason-code, status-machine, and
// before/after quantity snapshot decisions.
package stockadjustment

import "time"

// Status is the adjustment header's state machine. Matches the mock's
// own status filter exactly (Draft / Pending Approval / Approved /
// Rejected) — no separate "COMPLETED" stage, since Approve itself is
// the one and only inventory-mutating step (unlike Receiving/Putaway/
// Picking, which separate "the document exists" from "confirm moved
// stock" because those support partial, repeatable confirmation; an
// adjustment is a single atomic correction with no partial-application
// concept anywhere in the frontend).
type Status string

const (
	StatusDraft    Status = "DRAFT"
	StatusPending  Status = "PENDING"
	StatusApproved Status = "APPROVED"
	StatusRejected Status = "REJECTED"
)

// CanEdit reports whether header/item fields may still change (PUT) —
// only DRAFT, matching Receiving's own CanEdit reasoning: once
// submitted for approval, the numbers under review shouldn't shift.
func (s Status) CanEdit() bool {
	return s == StatusDraft
}

// CanConfirm reports whether Confirm's APPROVE/REJECT actions may run.
func (s Status) CanConfirm() bool {
	return s == StatusPending
}

func (s Status) IsValid() bool {
	switch s {
	case StatusDraft, StatusPending, StatusApproved, StatusRejected:
		return true
	default:
		return false
	}
}

// AdjustType mirrors StockAdjustmentView.vue's Adjustment Type <select>.
// INCREASE maps to inventory.AddStockTx, DECREASE to
// inventory.RemoveStockTx — see service.go's Approve.
type AdjustType string

const (
	AdjustIncrease AdjustType = "INCREASE"
	AdjustDecrease AdjustType = "DECREASE"
)

func (t AdjustType) IsValid() bool {
	switch t {
	case AdjustIncrease, AdjustDecrease:
		return true
	default:
		return false
	}
}

// Reason is a closed set matching StockAdjustmentView.vue's Reason
// <select> options verbatim — human-readable strings, not synthesized
// codes, per "do not invent codes if the frontend already defines
// them."
type Reason string

const (
	ReasonCycleCountVariance Reason = "Cycle Count Variance"
	ReasonDamagedGoods       Reason = "Damaged Goods"
	ReasonLostGoods          Reason = "Lost Goods"
	ReasonFoundGoods         Reason = "Found Goods"
	ReasonSystemCorrection   Reason = "System Correction"
)

func (r Reason) IsValid() bool {
	switch r {
	case ReasonCycleCountVariance, ReasonDamagedGoods, ReasonLostGoods, ReasonFoundGoods, ReasonSystemCorrection:
		return true
	default:
		return false
	}
}

// Adjustment is the GORM model for the stock_adjustments table
// (migrations/0023). SourceStockCountID (migrations/0031, Phase 17) is
// nil for a manually-created adjustment and set only when this document
// was generated by internal/stockcount's CreateAdjustments — the real,
// joinable replacement for what used to be only a free-text remark
// mentioning the count's number.
type Adjustment struct {
	ID                 int64      `gorm:"column:id;primaryKey"`
	AdjustmentNo       string     `gorm:"column:adjustment_no"`
	Status             Status     `gorm:"column:status"`
	CreatedBy          *int64     `gorm:"column:created_by"`
	ApprovedBy         *int64     `gorm:"column:approved_by"`
	SourceStockCountID *int64     `gorm:"column:source_stock_count_id"`
	CreatedAt          time.Time  `gorm:"column:created_at"`
	UpdatedAt          time.Time  `gorm:"column:updated_at"`
	ApprovedAt         *time.Time `gorm:"column:approved_at"`
}

func (Adjustment) TableName() string { return "stock_adjustments" }

// Item is the GORM model for the stock_adjustment_items table
