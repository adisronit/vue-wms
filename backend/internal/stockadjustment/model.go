// Aging is Phase 20's follow-up-visibility computation for one
// adjustment — never stored, always derived fresh from the row's own
// status/updated_at at read time, so it can never drift out of sync
// with reality the way a duplicated stored column could.
type Aging struct {
	PendingSince        *time.Time
	AgeHours            *int
	AgeDays             *float64
	IsOverdue           bool
	PendingWarningHours int
}

// pendingAging computes Aging for a single adjustment. Only ever
// non-zero for a currently-PENDING adjustment — DRAFT (not yet
// submitted, nobody is waiting on it), APPROVED, and REJECTED (already
// resolved) all return the zero Aging{PendingWarningHours: warningHours,
// IsOverdue: false}, which is this phase's own explicit requirement
// ("approved/rejected not overdue").
//
// pendingSince is updated_at, not created_at, and deliberately reuses
// that existing column rather than adding a new one: Update (PUT
// /stock-adjustments/{id}) is only ever allowed while still DRAFT (see
// Status.CanEdit), so once a document reaches PENDING — whether at
// creation (CreateRequest.Status=PENDING) or via a later DRAFT->PENDING
// submission — nothing touches its updated_at again until Confirm
// resolves it. That makes updated_at an exact "became pending at"
// timestamp for as long as the status stays PENDING, with no
// duplicated/stored age value anywhere.
func pendingAging(status Status, updatedAt time.Time, now time.Time, warningHours int) Aging {
	if status != StatusPending {
		return Aging{PendingWarningHours: warningHours}
	}
	since := updatedAt
	elapsed := now.Sub(since)
	hours := int(elapsed.Hours())
	days := roundToOneDecimal(elapsed.Hours() / 24)
	return Aging{
		PendingSince:        &since,
		AgeHours:            &hours,
		AgeDays:             &days,
		IsOverdue:           hours >= warningHours,
		PendingWarningHours: warningHours,
	}
}

func roundToOneDecimal(v float64) float64 {
	return float64(int(v*10+0.5)) / 10
}

// overdueCutoff and olderThanCutoff are the pure cutoff-timestamp
// computations behind the repository's own overdue/older_than_days SQL
// filters (`sa.updated_at <= cutoff`) — extracted so the arithmetic
// itself has a unit-testable surface independent of the DB query that
// uses it, the same "extract the pure part" precedent Phase 18's
// applyCancel established.
func overdueCutoff(now time.Time, warningHours int) time.Time {
	return now.Add(-time.Duration(warningHours) * time.Hour)
}

func olderThanCutoffTime(now time.Time, days int) time.Time {
	return now.AddDate(0, 0, -days)
}
